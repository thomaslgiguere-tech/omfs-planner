"""Object roles: what each object is in the surgical plan (bone, teeth, scan, segment, ...).

The role is stored on every object as `obj.omfs.role`, so it is saved in the .blend file.
Roles are generic on purpose: a genioplasty segment, a Le Fort I maxilla or a BSSO distal
segment are all just "SEGMENT" objects.
"""

import re
from pathlib import Path

import bpy

ROLES = (
    ('BONE', "Bone", "CT/CBCT bone segmentation (locked by default)"),
    ('TEETH', "Teeth", "Teeth segmented from the CT/CBCT"),
    ('SCAN', "Scan", "Intraoral scan"),
    ('NERVE', "Nerve", "Inferior alveolar nerve canal segmented from the CT/CBCT"),
    ('SKIN', "Skin", "Skin surface segmented from the CT/CBCT"),
    ('SEGMENT', "Segment", "Osteotomy segment that will be moved"),
    ('GUIDE', "Guide", "Surgical guide"),
    ('LANDMARK', "Landmark", "Anatomical landmark clicked on a surface"),
    ('REFERENCE', "Reference", "Reference frame and its planes"),
    ('CUT', "Cut", "Osteotomy plane"),
    ('BLOCK', "Block", "Mobile block: Empty carrying an arch and what moves with it"),
    ('MARKER', "Marker", "Visual marker, never a constraint (e.g. star below a foramen)"),
    ('ARCH', "Arch curve", "Curve along the dental arch that drives a splint or cap"),
    ('ANALYSIS', "Analysis", "Overlay shown by Section & Analysis (e.g. an intersection), removable in one click"),
    ('OTHER', "Other", "Anything else"),
)

# Viewport colours (RGBA, 0-1), shown when viewport shading colour is set to "Object".
COLORS = {
    'BONE': (0.90, 0.84, 0.70, 1.0),     # ivory
    'TEETH': (0.55, 0.75, 0.95, 1.0),    # light blue
    'SCAN': (0.95, 0.60, 0.60, 1.0),     # gingiva pink
    'NERVE': (0.95, 0.85, 0.20, 1.0),    # yellow
    'SKIN': (0.85, 0.68, 0.58, 1.0),     # skin tone
    'SEGMENT': (0.55, 0.85, 0.55, 1.0),  # green
    'GUIDE': (0.95, 0.70, 0.30, 1.0),    # orange
    'LANDMARK': (1.00, 0.20, 0.60, 1.0), # magenta
    'REFERENCE': (0.30, 0.55, 1.00, 0.15),  # each plane gets its own colour (reference_frame.py)
    'CUT': (1.00, 0.85, 0.10, 0.35),     # transparent yellow
    'BLOCK': (0.60, 0.60, 0.60, 1.0),    # Empty: colour unused
    'MARKER': (1.00, 0.90, 0.00, 1.0),   # yellow
    'ARCH': (1.00, 0.55, 0.10, 1.0),     # orange
    'ANALYSIS': (1.00, 0.10, 0.10, 1.0), # red
    'OTHER': (0.60, 0.60, 0.60, 1.0),    # grey
}

# Everything segmented from the CT/CBCT stays where it is: it defines the patient.
LOCKED_BY_DEFAULT = {'BONE', 'TEETH', 'NERVE', 'SKIN'}

# Helpers drawn in the viewport, not anatomy: clicks to place landmarks go through them.
NOT_SURFACES = {'LANDMARK', 'REFERENCE', 'CUT', 'MARKER', 'BLOCK', 'ANALYSIS', 'ARCH'}

# Filename keywords, checked in this order (a file called "ios_teeth" is a scan, not teeth,
# and "mandibular canal" is a nerve, not bone).
# Short keywords (< 4 letters) must be a whole word, so "os" does not match inside "ios".
KEYWORDS = (
    ('SCAN', ("scan", "ios", "intraoral", "upperjaw", "lowerjaw", "itero", "trios", "medit")),
    ('NERVE', ("nerve", "nerf", "canal", "ian")),
    ('SKIN', ("skin", "peau", "softtissue", "soft_tissue", "visage")),
    ('TEETH', ("teeth", "tooth", "dent", "dents", "dentition")),
    ('BONE', ("bone", "mandible", "mandibule", "maxilla", "maxillaire", "skull", "crane",
              "crâne", "os", "mand", "chin", "menton", "symphysis")),
)


def role_from_filename(filename):
    stem = Path(filename).stem.lower()
    words = [w for w in re.split(r"[^a-zâ0-9]+", stem) if w]
    for role, keywords in KEYWORDS:
        for keyword in keywords:
            if len(keyword) < 4:
                if keyword in words:
                    return role
            elif keyword in stem:
                return role
    return 'OTHER'


def apply_role_color(obj):
    obj.color = COLORS[obj.omfs.role]


def _on_role_changed(self, context):
    apply_role_color(self.id_data)


class OMFS_ObjectProperties(bpy.types.PropertyGroup):
    role: bpy.props.EnumProperty(name="Role", items=ROLES, default='OTHER', update=_on_role_changed)
    # Landmarks only (see landmarks.py): which landmark this is, and the mesh it was placed on.
    landmark: bpy.props.StringProperty(name="Landmark")
    surface: bpy.props.StringProperty(name="Placed on")
    # Objects generated by an operation (e.g. a cut): the name of what made them, so redoing
    # the operation can replace them.
    made_by: bpy.props.StringProperty(name="Made by")


def register():
    bpy.utils.register_class(OMFS_ObjectProperties)
    bpy.types.Object.omfs = bpy.props.PointerProperty(type=OMFS_ObjectProperties)


def unregister():
    del bpy.types.Object.omfs
    bpy.utils.unregister_class(OMFS_ObjectProperties)
